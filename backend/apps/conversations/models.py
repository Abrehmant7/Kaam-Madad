"""Private conversation, versioned quotations and agreement-gap findings (M7: MSG-01..03, QT-01..03, GAP-01..03).

Everything hangs off an M6 ``Invitation`` (one conversation per invitation; a later invitation has
its own conversation). Only the request owner and the invited worker are participants. Writes
(messages, quotes) are allowed only while the invitation is ``active``; history stays readable.

- ``Message``: immutable once sent. Text, or a voice note whose ORIGINAL audio (``audio_clip``), the
  speech-to-text proposal (``interpreted_text``) and the sender-approved caption (``text``) are kept
  separately. ``client_id`` (generated by the sender's device) makes retries return the same message.
- ``Quote``: the worker's structured quotation. A ``draft`` is editable; submitting freezes it as the
  next ``version`` and supersedes the previous submitted version. PKR amounts are decimals; totals are
  computed in backend code; unknown amounts stay NULL (shown as unknown, never as zero).
- ``GapFinding``: a clarification prompt tied to ONE quote version, with its source statements and,
  once handled, the recorded resolution (who, when, explicit corrected terms).
"""

from __future__ import annotations

import uuid

from django.conf import settings
from django.db import models
from django.db.models import F, Q
from django.utils import timezone
from django.utils.translation import gettext_lazy as _

from apps.invitations.models import Invitation


class Message(models.Model):
    class Kind(models.TextChoices):
        TEXT = "text", _("Text")
        VOICE = "voice", _("Voice note")

    class CaptionStatus(models.TextChoices):
        NONE = "", _("Text message")
        APPROVED = "approved", _("Caption checked by the sender")
        TYPED = "typed", _("Caption typed by the sender (no automatic caption)")
        UNAVAILABLE = "unavailable", _("Caption unavailable")

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    invitation = models.ForeignKey(Invitation, on_delete=models.PROTECT, related_name="messages")
    sender = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.PROTECT, related_name="+")
    sender_role = models.CharField(max_length=16)
    client_id = models.UUIDField(help_text=_("Generated by the sender's device; makes retries safe."))
    kind = models.CharField(max_length=8, choices=Kind.choices)
    text = models.TextField(blank=True, default="", help_text=_("Text message, or the sender-approved caption."))
    caption_status = models.CharField(max_length=16, choices=CaptionStatus.choices, blank=True, default="")
    interpreted_text = models.TextField(blank=True, default="", help_text=_("Automatic caption proposal (not edited)."))
    audio_clip = models.ForeignKey("voice.AudioClip", null=True, blank=True, on_delete=models.PROTECT, related_name="+")
    transcription = models.ForeignKey("voice.Transcription", null=True, blank=True, on_delete=models.SET_NULL, related_name="+")
    created_at = models.DateTimeField(default=timezone.now)

    class Meta:
        ordering = ["created_at", "id"]
        indexes = [models.Index(fields=["invitation", "created_at"], name="msg_invitation_time_idx")]
        constraints = [
            models.UniqueConstraint(fields=["invitation", "sender", "client_id"], name="msg_client_id_once"),
            models.UniqueConstraint(fields=["audio_clip"], condition=Q(audio_clip__isnull=False), name="msg_clip_once"),
            models.CheckConstraint(
                condition=(Q(kind="text") & Q(audio_clip__isnull=True) & ~Q(text="") & Q(caption_status=""))
                | (Q(kind="voice") & Q(audio_clip__isnull=False) & ~Q(caption_status="")),
                name="msg_kind_consistent",
            ),
        ]

    def __str__(self) -> str:
        return f"Message {str(self.id)[:8]} ({self.kind})"


class Quote(models.Model):
    class Status(models.TextChoices):
        DRAFT = "draft", _("Draft (not sent)")
        SUBMITTED = "submitted", _("Submitted (current)")
        SUPERSEDED = "superseded", _("Superseded by a newer version")

    class LabourBasis(models.TextChoices):
        TOTAL = "total", _("Total for the job")
        PER_ITEM = "per_item", _("Per item")

    class Materials(models.TextChoices):
        INCLUDED = "included", _("Worker supplies; included in the labour price")
        WORKER_EXTRA = "worker_extra", _("Worker supplies; charged separately")
        CUSTOMER = "customer", _("Customer supplies and pays for materials")
        NONE = "none", _("No materials needed")

    class VisitFee(models.TextChoices):
        NONE = "none", _("No visit fee")
        CHARGED = "charged", _("Visit fee charged")
        WAIVED_IF_HIRED = "waived_if_hired", _("Visit fee waived if the repair goes ahead")
        INCLUDED = "included", _("Visit included in the labour price")

    class CheckStatus(models.TextChoices):
        NOT_RUN = "not_run", _("Not run")
        PASSED = "passed", _("No possible conflicts found")
        FINDINGS = "findings", _("Possible conflicts found")
        UNAVAILABLE = "unavailable", _("Automated check could not run")

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    invitation = models.ForeignKey(Invitation, on_delete=models.PROTECT, related_name="quotes")
    version = models.PositiveIntegerField(null=True, blank=True)
    status = models.CharField(max_length=16, choices=Status.choices, default=Status.DRAFT)

    inspection_only = models.BooleanField(default=False)
    scope = models.TextField(blank=True, default="")
    quantity = models.PositiveSmallIntegerField(null=True, blank=True)
    labour_amount = models.DecimalField(max_digits=10, decimal_places=2, null=True, blank=True)
    labour_basis = models.CharField(max_length=16, choices=LabourBasis.choices, default=LabourBasis.TOTAL)
    materials = models.CharField(max_length=16, choices=Materials.choices, blank=True, default="")
    materials_amount = models.DecimalField(
        max_digits=10, decimal_places=2, null=True, blank=True, help_text=_("Only when charged separately; empty = unknown."),
    )
    visit_fee = models.DecimalField(max_digits=10, decimal_places=2, null=True, blank=True)
    visit_fee_treatment = models.CharField(max_length=16, choices=VisitFee.choices, default=VisitFee.NONE)
    exclusions = models.TextField(blank=True, default="")
    start_at = models.DateTimeField(null=True, blank=True)
    end_at = models.DateTimeField(null=True, blank=True)

    totals = models.JSONField(null=True, blank=True, help_text=_("Computed by the backend when submitted."))
    created_at = models.DateTimeField(default=timezone.now)
    updated_at = models.DateTimeField(auto_now=True)
    submitted_at = models.DateTimeField(null=True, blank=True)
    superseded_at = models.DateTimeField(null=True, blank=True)
    expires_at = models.DateTimeField(null=True, blank=True)

    check_status = models.CharField(max_length=16, choices=CheckStatus.choices, default=CheckStatus.NOT_RUN)
    check_provider = models.CharField(max_length=32, blank=True, default="")
    check_simulated = models.BooleanField(default=False)
    checked_at = models.DateTimeField(null=True, blank=True)
    check_failure = models.CharField(max_length=64, blank=True, default="")
    manual_review_by = models.ForeignKey(settings.AUTH_USER_MODEL, null=True, blank=True, on_delete=models.PROTECT, related_name="+")
    manual_review_at = models.DateTimeField(null=True, blank=True)

    class Meta:
        ordering = ["-version", "-created_at"]
        constraints = [
            models.UniqueConstraint(fields=["invitation", "version"], condition=Q(version__isnull=False), name="quote_version_once"),
            models.UniqueConstraint(fields=["invitation"], condition=Q(status="draft"), name="quote_one_draft"),
            models.UniqueConstraint(fields=["invitation"], condition=Q(status="submitted"), name="quote_one_current"),
            models.CheckConstraint(
                condition=Q(status="draft", version__isnull=True, submitted_at__isnull=True)
                | (~Q(status="draft") & Q(version__isnull=False, submitted_at__isnull=False, expires_at__isnull=False,
                                         totals__isnull=False)),
                name="quote_submitted_is_frozen_shape",
            ),
            # Drafts may be inconsistent while being edited (reported as issues); submitted versions may not.
            models.CheckConstraint(
                condition=Q(status="draft") | Q(end_at__gt=F("start_at")),
                name="quote_end_after_start",
            ),
            models.CheckConstraint(
                condition=(Q(labour_amount__isnull=True) | Q(labour_amount__gte=0))
                & (Q(materials_amount__isnull=True) | Q(materials_amount__gte=0))
                & (Q(visit_fee__isnull=True) | Q(visit_fee__gte=0)),
                name="quote_amounts_not_negative",
            ),
        ]

    def __str__(self) -> str:
        return f"Quote v{self.version or 'draft'} · {self.get_status_display()}"


class GapFinding(models.Model):
    class Source(models.TextChoices):
        RULE = "rule", _("Backend rule")
        AI = "ai", _("Automated (AI) check")

    class Status(models.TextChoices):
        OPEN = "open", _("Needs clarification")
        RESOLVED = "resolved", _("Resolved")

    class Resolution(models.TextChoices):
        CLARIFIED = "clarified", _("Clarified")
        NOT_A_CONFLICT = "not_a_conflict", _("Not a conflict (terms confirmed)")

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    quote = models.ForeignKey(Quote, on_delete=models.CASCADE, related_name="findings")
    source = models.CharField(max_length=8, choices=Source.choices)
    code = models.CharField(max_length=40)
    blocking = models.BooleanField(default=True)
    question = models.TextField(blank=True, default="")
    ask = models.CharField(max_length=16, default="both")
    sources = models.JSONField(default=list)
    status = models.CharField(max_length=16, choices=Status.choices, default=Status.OPEN)
    resolution = models.CharField(max_length=16, choices=Resolution.choices, blank=True, default="")
    resolution_note = models.TextField(blank=True, default="")
    resolved_by = models.ForeignKey(settings.AUTH_USER_MODEL, null=True, blank=True, on_delete=models.PROTECT, related_name="+")
    resolved_role = models.CharField(max_length=16, blank=True, default="")
    resolved_at = models.DateTimeField(null=True, blank=True)
    created_at = models.DateTimeField(default=timezone.now)

    class Meta:
        ordering = ["created_at"]
        constraints = [
            models.CheckConstraint(
                condition=Q(status="open", resolved_at__isnull=True, resolution="")
                | (Q(status="resolved", resolved_at__isnull=False) & ~Q(resolution="") & ~Q(resolution_note="")),
                name="finding_resolution_recorded",
            ),
        ]
