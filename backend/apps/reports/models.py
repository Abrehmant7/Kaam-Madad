"""Private misconduct reports, staff moderation and contact blocks (M10: REP-01..03, SAFE-01..02).

- ``Report``: filed by a participant about the OTHER participant of an existing invitation or booking. The
  reported user is derived on the server from that interaction (never chosen by the client). Statuses: open,
  reviewing, resolved, dismissed. A report never changes a booking or punishes anyone by itself.
- ``ReportEvidence``: the reporter's voice statement and optional evidence (images re-encoded without metadata,
  or audio). Private to the reporter and to staff holding ``reports.view_evidence``; every staff access is
  recorded in ``EvidenceAccess``. Report audio is never transcribed or sent to any provider.
- ``ReportMessage``: the reporter's replies, staff messages INTENDED for the reporter, and internal staff notes
  (never shown to the reporter). The reported user sees none of it.
- ``ReportDecision``: the audit log — every status change, information request and account action, with actor,
  time, reason and old/new state.
- ``ContactBlock``: one user blocks further contact with the other participant of an interaction. Enforced for
  new invitations, messages, quotes and bookings between the pair; history, reports and existing bookings stay.
"""

from __future__ import annotations

import uuid

from django.conf import settings
from django.db import models
from django.db.models import F, Q
from django.utils import timezone
from django.utils.translation import gettext_lazy as _


def evidence_upload_path(instance, filename: str) -> str:
    extension = {"image/jpeg": ".jpg", "image/png": ".png", "image/webp": ".webp"}.get(instance.mime_type, "")
    return f"report-evidence/{timezone.now():%Y/%m}/{uuid.uuid4().hex}{extension}"


class Report(models.Model):
    class Category(models.TextChoices):
        HARASSMENT = "harassment", _("Harassment")
        THREATS = "threats", _("Threats")
        IMPERSONATION = "impersonation", _("Suspected impersonation")
        NO_SHOW = "no_show", _("No-show")
        PROPERTY_WORK = "property_work", _("Property or work issue")
        OTHER = "other", _("Other")

    class Status(models.TextChoices):
        OPEN = "open", _("Open")
        REVIEWING = "reviewing", _("Reviewing")
        RESOLVED = "resolved", _("Resolved")
        DISMISSED = "dismissed", _("Dismissed")

    CLOSED = (Status.RESOLVED, Status.DISMISSED)

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    reporter = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.PROTECT, related_name="reports_filed")
    reporter_role = models.CharField(max_length=16)
    reported = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.PROTECT, related_name="+")
    invitation = models.ForeignKey("invitations.Invitation", on_delete=models.PROTECT, related_name="+")
    booking = models.ForeignKey("bookings.Booking", null=True, blank=True, on_delete=models.PROTECT, related_name="+")
    client_id = models.UUIDField(help_text=_("Generated by the reporter's device; makes retries safe."))
    category = models.CharField(max_length=16, choices=Category.choices)
    description = models.TextField(blank=True, default="")
    status = models.CharField(max_length=16, choices=Status.choices, default=Status.OPEN)
    awaiting_reply = models.BooleanField(default=False, help_text=_("Staff asked the reporter for more information."))
    created_at = models.DateTimeField(default=timezone.now)
    updated_at = models.DateTimeField(auto_now=True)
    closed_at = models.DateTimeField(null=True, blank=True)

    class Meta:
        ordering = ["-created_at"]
        indexes = [models.Index(fields=["status", "created_at"], name="report_queue_idx")]
        permissions = [
            ("review_report", "Can review reports and record decisions"),
            ("view_evidence", "Can open report evidence (every access is recorded)"),
            ("take_account_action", "Can restrict, suspend or lift restrictions on accounts"),
        ]
        constraints = [
            models.UniqueConstraint(fields=["reporter", "client_id"], name="report_client_id_once"),
            models.CheckConstraint(condition=~Q(reporter=F("reported")), name="report_not_about_self"),
            models.CheckConstraint(
                condition=Q(status__in=["open", "reviewing"], closed_at__isnull=True)
                | Q(status__in=["resolved", "dismissed"], closed_at__isnull=False),
                name="report_closed_has_time",
            ),
        ]

    def __str__(self) -> str:
        return f"Report {str(self.id)[:8]} · {self.get_category_display()} · {self.get_status_display()}"


class ReportEvidence(models.Model):
    class Kind(models.TextChoices):
        IMAGE = "image", _("Image")
        AUDIO = "audio", _("Audio")

    class Role(models.TextChoices):
        STATEMENT = "statement", _("Voice statement")
        EVIDENCE = "evidence", _("Evidence")

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    report = models.ForeignKey(Report, on_delete=models.PROTECT, related_name="evidence")
    kind = models.CharField(max_length=8, choices=Kind.choices)
    role = models.CharField(max_length=12, choices=Role.choices, default=Role.EVIDENCE)
    file = models.FileField(upload_to=evidence_upload_path, max_length=200, blank=True)
    audio_clip = models.ForeignKey("voice.AudioClip", null=True, blank=True, on_delete=models.SET_NULL, related_name="+")
    mime_type = models.CharField(max_length=32)
    size_bytes = models.PositiveIntegerField()
    created_at = models.DateTimeField(default=timezone.now)
    deleted_at = models.DateTimeField(null=True, blank=True, help_text=_("Content removed under the retention policy."))

    class Meta:
        ordering = ["created_at"]
        constraints = [
            models.UniqueConstraint(fields=["audio_clip"], condition=Q(audio_clip__isnull=False), name="evidence_clip_once"),
        ]

    def __str__(self) -> str:
        return f"{self.get_role_display()} ({self.kind}) for report {str(self.report_id)[:8]}"


class ReportMessage(models.Model):
    class Kind(models.TextChoices):
        REPORTER_REPLY = "reporter_reply", _("Reply from the reporter")
        TO_REPORTER = "to_reporter", _("Staff message to the reporter")
        INTERNAL = "internal", _("Internal staff note (never shown to the reporter)")

    id = models.BigAutoField(primary_key=True)
    report = models.ForeignKey(Report, on_delete=models.PROTECT, related_name="messages")
    kind = models.CharField(max_length=16, choices=Kind.choices)
    author = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.PROTECT, related_name="+")
    text = models.TextField()
    created_at = models.DateTimeField(default=timezone.now)

    class Meta:
        ordering = ["created_at", "id"]


class ReportDecision(models.Model):
    class Action(models.TextChoices):
        MARK_REVIEWING = "mark_reviewing", _("Marked as reviewing")
        REQUEST_INFO = "request_info", _("Asked the reporter for more information")
        RESOLVE = "resolve", _("Resolved")
        DISMISS = "dismiss", _("Dismissed")
        NOTE = "note", _("Internal note only")
        RESTRICT = "restrict", _("Restricted the reported account")
        LIFT_RESTRICTION = "lift_restriction", _("Lifted the restriction")
        SUSPEND = "suspend", _("Suspended the reported account (no login)")
        REACTIVATE = "reactivate", _("Reactivated the reported account")

    ACCOUNT_ACTIONS = (Action.RESTRICT, Action.LIFT_RESTRICTION, Action.SUSPEND, Action.REACTIVATE)

    id = models.BigAutoField(primary_key=True)
    report = models.ForeignKey(Report, on_delete=models.PROTECT, related_name="decisions")
    action = models.CharField(max_length=24, choices=Action.choices)
    actor = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.PROTECT, related_name="+")
    reason = models.TextField()
    old_state = models.JSONField(default=dict)
    new_state = models.JSONField(default=dict)
    at = models.DateTimeField(default=timezone.now)

    class Meta:
        ordering = ["at", "id"]
        constraints = [models.CheckConstraint(condition=~Q(reason=""), name="decision_has_reason")]


class EvidenceAccess(models.Model):
    """Every time staff open report evidence (who, what, when). Never the content."""

    id = models.BigAutoField(primary_key=True)
    evidence = models.ForeignKey(ReportEvidence, on_delete=models.PROTECT, related_name="accesses")
    staff = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.PROTECT, related_name="+")
    at = models.DateTimeField(default=timezone.now)

    class Meta:
        ordering = ["-at"]


class ContactBlock(models.Model):
    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    blocker = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.CASCADE, related_name="+")
    blocked = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.CASCADE, related_name="+")
    invitation = models.ForeignKey("invitations.Invitation", on_delete=models.PROTECT, related_name="+")
    created_at = models.DateTimeField(default=timezone.now)

    class Meta:
        ordering = ["-created_at"]
        constraints = [
            models.UniqueConstraint(fields=["blocker", "blocked"], name="block_pair_once"),
            models.CheckConstraint(condition=~Q(blocker=F("blocked")), name="block_not_self"),
        ]
